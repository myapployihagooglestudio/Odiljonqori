/**
 * Returns the Ayahs for a given Surah.
 * If verified authentic text is available in local dataset, it returns that.
 * Otherwise, it creates a properly initialized Ayah array according to the Surah's
 * canonical ayahCount, marked as "missing" timestamps, ready for authentic admin entry.
 */
export function getAyahsForSurah(surahNumber: number, ayahCount: number, startPage: number, juzNumber: number): Ayah[] {
  if (VERIFIED_SURAHS_AYAHS[surahNumber]) {
    return VERIFIED_SURAHS_AYAHS[surahNumber];
  }

  // Generate template Ayahs for this Surah with canonical ayah numbers
  const ayahs: Ayah[] = [];
  for (let i = 1; i <= ayahCount; i++) {
    ayahs.push({
      id: `${surahNumber}-${i}`,
      surahNumber,
      ayahNumber: i,
      textArabic: `[${surahNumber}:${i}] Oyat matni admin tomonidan tekshirilishi kutilmoqda`,
      textUzbek: `${i}-oyat tarjimasi admin paneldan to'ldiriladi.`,
      transliteration: `${surahNumber}:${i}`,
      juzNumber,
      pageNumber: startPage,
      startMs: null,
      endMs: null,
      timestampStatus: "missing",
    });
  }
  return ayahs;
}
